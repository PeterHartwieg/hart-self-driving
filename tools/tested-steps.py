#!/usr/bin/env python3
import json
import pathlib
import sys

FAULTS = ("contact", "near-miss", "stuck", "intrusion", "far-side-early", "missed-gate", "exit-lane", "exit-heading")
repo = pathlib.Path(__file__).resolve().parent.parent
lengths = {}
files = [(a.split(":")[0], set(a.split(":")[1].split(",")) if ":" in a else None) for a in sys.argv[1:]]
for cars in [pathlib.Path(p).parent / "cars.jsonl" for p, _ in files] + [repo / "build/tests/first/cars.jsonl"]:
    if cars.exists():
        for line in open(cars, encoding="utf-8"):
            car = json.loads(line)
            lengths.setdefault(car["name"], car["length"])

# Cases from builds before 0.1.34 could run out round a dead end (the lane back): their failures there are the
# case's, not the manoeuvre's. The lane graph dump tells them apart.
graph_file = repo / "build/sol-tests/lane-graph.json"
positions = [w["p"] for w in json.load(open(graph_file))] if graph_file.exists() else None


def doubles_back(route, start):
    if positions is None:
        return False
    import math
    for k in range(max(start, 1), len(route) - 1):
        a, b, c = positions[route[k - 1]], positions[route[k]], positions[route[k + 1]]
        u = (b[0] - a[0], b[2] - a[2])
        v = (c[0] - b[0], c[2] - b[2])
        lu, lv = math.hypot(*u), math.hypot(*v)
        if lu > 0.1 and lv > 0.1 and (u[0] * v[0] + u[1] * v[1]) / (lu * lv) < 0.5:
            return True
    return False


shortest = {}
why = {}
for path, kinds in files:
    for line in open(path, encoding="utf-8"):
        if not line.strip():
            continue
        run = json.loads(line)
        fixture = run.get("fixture")
        if run.get("verdict") != "fail" or not fixture or fixture.get("IsMutation") or fixture["Kind"] == "Ride":
            continue
        if kinds is not None and fixture["Manoeuvre"] not in kinds:
            continue
        reasons = [r for r in run["judge"]["Reasons"] if r.split(":")[0] in FAULTS]
        if not reasons or "entry" not in run["judge"]["GatesPassed"]:
            continue
        route, entry = fixture["Route"], fixture["EntryIndex"]
        if doubles_back(route, fixture["ExitIndex"] + 1):
            continue
        step = (route[entry], route[entry + 1])
        length = lengths.get(run["car"])
        if length is None:
            continue
        if step not in shortest or length < shortest[step]:
            shortest[step] = length
            why[step] = f"{run['case']} {run['car']} {' '.join(reasons)} (run {run['run']})"

entries = "\n".join(f"            {{ ({a}, {b}), {l}f }}, // {why[(a, b)]}" for (a, b), l in sorted(shortest.items()))
source = f"""#nullable enable
using System.Collections.Generic;

namespace DrivenRides
{{
    // Generated by tools/tested-steps.py from turn test results (docs/turn-tests.md); don't edit by hand.
    // Manoeuvres that failed in a turn test, with the shortest car (metres) that failed each: the planner avoids
    // them for cars at least that long. Waypoint indices are the game's lane data, so the list belongs to one
    // game build.
    internal static class TestedSteps
    {{
        private static readonly Dictionary<(int, int), float> Shortest = new Dictionary<(int, int), float>
        {{
{entries}
        }};

        public static int Count => Shortest.Count;

        public static bool Has(int from, int to) => Shortest.ContainsKey((from, to));

        public static bool Blocks(int from, int to, float carLength) =>
            Shortest.TryGetValue((from, to), out var length) && carLength >= length - 0.01f;
    }}
}}
"""
(repo / "unity/DrivenRides/Scripts/TestedSteps.cs").write_text(source.replace("\n\n        }};", "\n        }};"), encoding="utf-8")
print(f"{len(shortest)} steps written.")
